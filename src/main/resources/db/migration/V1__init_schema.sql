CREATE TABLE exam_answers
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    question_id INTEGER,
    is_correct  BOOLEAN,
    answer_text TEXT,
    CONSTRAINT pk_exam_answers PRIMARY KEY (id)
);

CREATE TABLE exam_questions
(
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    exam_id       UUID,
    question_text TEXT,
    point         DOUBLE PRECISION,
