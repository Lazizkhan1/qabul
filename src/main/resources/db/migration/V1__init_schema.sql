CREATE TABLE application_settings
(
    key           VARCHAR(255)                NOT NULL,
    value_boolean BOOLEAN                     NOT NULL,
    updated_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_by    UUID,
    CONSTRAINT pk_application_settings PRIMARY KEY (key)
);

CREATE TABLE applications
(
    id               UUID         NOT NULL,
    user_id          UUID         NOT NULL,
    tuition_id       UUID         NOT NULL,
    status           VARCHAR(255) NOT NULL,
    firstname        VARCHAR(255) NOT NULL,
    lastname         VARCHAR(255) NOT NULL,
    middlename       VARCHAR(255),
    birth_date       date         NOT NULL,
    gender           CHAR(1)      NOT NULL,
    jshshir          VARCHAR(255) NOT NULL,
    passport_series  VARCHAR(255) NOT NULL,
    address          VARCHAR(255) NOT NULL,
    additional_phone VARCHAR(255),
    disability       INTEGER      NOT NULL,
    created_at       TIMESTAMP WITHOUT TIME ZONE,
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_applications PRIMARY KEY (id)
);

CREATE TABLE bachelor_certs
(
    id         UUID         NOT NULL,
    user_id    UUID,
    cert_id    VARCHAR(255) NOT NULL,
    university VARCHAR(255) NOT NULL,
    major      VARCHAR(255) NOT NULL,
    gpa        DOUBLE PRECISION,
    CONSTRAINT pk_bachelor_certs PRIMARY KEY (id)
);

CREATE TABLE cert_category
(
